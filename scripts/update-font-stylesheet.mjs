import { createHash } from "node:crypto";
import { mkdir, readdir, unlink, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const stylesheetUrl =
  "https://fonts.googleapis.com/css2?family=Alexandria:wght@400;500;600;700&family=LINE+Seed+JP:wght@400;700&display=swap";
const browserUserAgent =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 " +
  "Chrome/140.0.0.0 Safari/537.36";
const outputFile = resolve(
  fileURLToPath(new URL("../src/font-faces.css", import.meta.url))
);
const fontDirectory = resolve(
  fileURLToPath(new URL("../public/fonts/google", import.meta.url))
);
const fontPublicPath = "/fonts/google";
const licenseSources = new Map([
  [
    "alexandria-OFL.txt",
    "https://raw.githubusercontent.com/google/fonts/main/ofl/alexandria/OFL.txt"
  ],
  [
    "lineseedjp-OFL.txt",
    "https://raw.githubusercontent.com/google/fonts/main/ofl/lineseedjp/OFL.txt"
  ]
]);

const response = await fetch(stylesheetUrl, {
  headers: { "user-agent": browserUserAgent }
});
if (!response.ok) {
  throw new Error(
    `Failed to fetch the font stylesheet: ${response.status} ${response.statusText}`
  );
}

const source = await response.text();
const remoteUrls = validateRemoteStylesheet(source);
await mkdir(fontDirectory, { recursive: true });

const localPaths = new Map(
  remoteUrls.map((url) => [
    url,
    `${fontPublicPath}/${basename(new URL(url).pathname)}`
  ])
);
await downloadFonts(localPaths);
await downloadLicenses();
await removeObsoleteFontFiles(
  new Set([
    ...[...localPaths.values()].map((url) => basename(url)),
    ...licenseSources.keys()
  ])
);

let localizedSource = source;
for (const [remoteUrl, localPath] of localPaths) {
  localizedSource = localizedSource.replaceAll(remoteUrl, localPath);
}
validateLocalStylesheet(localizedSource);
const output =
  `/* Generated by scripts/update-font-stylesheet.mjs from ${stylesheetUrl}; font binaries are served locally. */\n` +
  `${localizedSource.trim()}\n`;
await writeFile(outputFile, output);

console.log(
  `Updated ${outputFile}: ${Buffer.byteLength(output)} bytes, ` +
    `sha256-${createHash("sha256").update(output).digest("base64url")}`
);

function validateRemoteStylesheet(stylesheet) {
  const faceCount = [...stylesheet.matchAll(/@font-face\s*\{/g)].length;
  const swapCount = [...stylesheet.matchAll(/font-display:\s*swap\s*;/g)].length;
  const families = new Set(
    [...stylesheet.matchAll(/font-family:\s*'([^']+)'\s*;/g)].map(
      (match) => match[1]
    )
  );
  const weightsByFamily = new Map();
  for (const block of stylesheet.matchAll(/@font-face\s*\{([^}]+)\}/gs)) {
    const family = /font-family:\s*'([^']+)'\s*;/.exec(block[1])?.[1];
    const weight = /font-weight:\s*(\d+)\s*;/.exec(block[1])?.[1];
    if (!family || !weight) {
      throw new Error("The font stylesheet contains an incomplete @font-face.");
    }
    const weights = weightsByFamily.get(family) ?? new Set();
    weights.add(weight);
    weightsByFamily.set(family, weights);
  }
  const urls = [
    ...stylesheet.matchAll(/url\((https:[^)]+)\)\s+format\('woff2'\)/g)
  ].map((match) => match[1]);

  if (faceCount === 0 || swapCount !== faceCount || urls.length !== faceCount) {
    throw new Error("The font stylesheet must use swap and one WOFF2 URL per face.");
  }
  if (
    families.size !== 2 ||
    !families.has("Alexandria") ||
    !families.has("LINE Seed JP")
  ) {
    throw new Error("The font stylesheet contains an unexpected family.");
  }
  assertWeights(weightsByFamily, "Alexandria", ["400", "500", "600", "700"]);
  assertWeights(weightsByFamily, "LINE Seed JP", ["400", "700"]);
  if (
    urls.some(
      (url) =>
        !url.startsWith("https://fonts.gstatic.com/") ||
        !url.endsWith(".woff2")
    )
  ) {
    throw new Error("The font stylesheet contains an unexpected font URL.");
  }
  return [...new Set(urls)];
}

function validateLocalStylesheet(stylesheet) {
  const urls = [...stylesheet.matchAll(/url\(([^)]+)\)\s+format\('woff2'\)/g)]
    .map((match) => match[1]);
  if (
    urls.length === 0 ||
    urls.some((url) => !url.startsWith(`${fontPublicPath}/`) || !url.endsWith(".woff2"))
  ) {
    throw new Error("The generated font stylesheet must use local WOFF2 URLs.");
  }
  if (stylesheet.includes("fonts.gstatic.com")) {
    throw new Error("The generated font stylesheet contains a remote font URL.");
  }
}

async function downloadFonts(localPaths) {
  const entries = [...localPaths];
  for (let start = 0; start < entries.length; start += 12) {
    await Promise.all(
      entries.slice(start, start + 12).map(async ([url, localPath]) => {
        const response = await fetch(url);
        if (!response.ok) {
          throw new Error(
            `Failed to fetch ${url}: ${response.status} ${response.statusText}`
          );
        }
        const buffer = Buffer.from(await response.arrayBuffer());
        if (buffer.subarray(0, 4).toString("ascii") !== "wOF2") {
          throw new Error(`${url} did not return a WOFF2 font.`);
        }
        await writeFile(resolve(fontDirectory, basename(localPath)), buffer);
      })
    );
  }
}

async function downloadLicenses() {
  await Promise.all(
    [...licenseSources].map(async ([filename, url]) => {
      const response = await fetch(url);
      if (!response.ok) {
        throw new Error(
          `Failed to fetch ${url}: ${response.status} ${response.statusText}`
        );
      }
      await writeFile(resolve(fontDirectory, filename), await response.text());
    })
  );
}

async function removeObsoleteFontFiles(expectedFiles) {
  for (const filename of await readdir(fontDirectory)) {
    if (
      (filename.endsWith(".woff2") || filename.endsWith("-OFL.txt")) &&
      !expectedFiles.has(filename)
    ) {
      await unlink(resolve(fontDirectory, filename));
    }
  }
}

function assertWeights(weightsByFamily, family, expected) {
  const actual = [...(weightsByFamily.get(family) ?? [])].sort();
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(
      `${family} weights changed: expected ${expected.join(", ")}, ` +
        `received ${actual.join(", ")}.`
    );
  }
}
